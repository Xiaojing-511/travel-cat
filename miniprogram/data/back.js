function pickBackText(seed) {
  if (!backText.length) return "";
  const s = String(seed || "");
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return backText[(h >>> 0) % backText.length];
}

